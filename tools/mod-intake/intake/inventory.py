"""What BotStory already has, so triage can say "already have it" or "conflicts": catalog/inventory.yaml.

    client:  generated from kaentake's src/feature_list.h (one entry per module) plus the v83 addresses each
             module's source file names; descriptions are written by hand and kept when the list is regenerated
    server:  kept by hand: BotStory server features, tools and client data. server_mod is the id in the P5
             server.mods registry once that exists (left empty until then)
"""
import re
import subprocess
from pathlib import Path

from . import rules
from . import yamlish

INVENTORY_HEADER = """Mods BotStory already has. Triage (mod_intake.py triage) matches release threads against these.
client: generated by 'mod_intake.py inventory' from kaentake src/feature_list.h; edit 'description' by hand
        (kept on regeneration), everything else comes from the source.
server: kept by hand. side = server | tool | data. server_mod = the P5 server.mods registry id, once it exists.
paths: where the feature lives in the server repo, for overlap hints."""

FEATURE_RE = re.compile(r'X\(\s*(\w+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*([01])\s*,\s*([^,]+?)\s*,\s*(\w+)\s*,'
                        r'\s*([\w:]+)\s*\)')
DEFINE_RE = re.compile(r"(?m)^[ \t]*(?:static[ \t]+)?(?:void|bool)[ \t]+(?:\w+::)*(\w+)[ \t]*\([ \t]*(?:void)?[ \t]*\)"
                       r"\s*\{")
FLAGS = {"FEATURE_CORE": "core", "FEATURE_SERVER_GATED": "server_gated", "FEATURE_LIVE": "live",
         "FEATURE_EARLY": "early", "FEATURE_DEFERRED": "deferred"}
FEATURE_LIST = "src/feature_list.h"


class InventoryError(Exception):
    pass


def parse_feature_list(text):
    entries = []
    for m in FEATURE_RE.finditer(text):
        flags = [FLAGS.get(f.strip(), f.strip().lower()) for f in m.group(4).split("|") if f.strip() != "0"]
        requires = m.group(5)
        entries.append({"id": m.group(1), "title": m.group(2).replace('\\"', '"'), "default": m.group(3) == "1",
                        "flags": flags, "requires": None if requires == "none" else requires,
                        "attach": m.group(6).split("::")[-1]})
    if not entries:
        raise InventoryError(f"no X(...) module lines found in {FEATURE_LIST}")
    return entries


class KaentakeSource:
    """Files of a kaentake checkout: at a git ref (read with git show, no checkout needed) or the work tree."""

    def __init__(self, repo, ref=None):
        self.repo = Path(repo)
        self.ref = ref
        if not (self.repo / ".git").exists():
            raise InventoryError(f"{self.repo} is not a kaentake git checkout (use --kaentake)")
        self.commit = self._git("rev-parse", "--verify", (ref or "HEAD") + "^{commit}").strip()

    def _git(self, *args):
        p = subprocess.run(["git", "-C", str(self.repo), *args], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if p.returncode:
            raise InventoryError(f"git {' '.join(args)}: {p.stderr.decode('utf-8', 'replace').strip()}")
        return p.stdout.decode("utf-8", "replace")

    def read(self, path):
        if self.ref:
            return self._git("show", f"{self.ref}:{path}")
        return (self.repo / path).read_text("utf-8", "replace")

    def sources(self):
        if self.ref:
            names = self._git("ls-tree", "-r", "--name-only", self.ref, "--", "src").splitlines()
        else:
            names = [p.relative_to(self.repo).as_posix() for p in (self.repo / "src").rglob("*")]
        return sorted(n for n in names if n.endswith((".cpp", ".h")) and "/wvs/" not in n and "/ztl/" not in n)


def scan_client(source):
    """feature_list.h modules with the file that defines each attach function and the addresses that file uses."""
    modules = parse_feature_list(source.read(FEATURE_LIST))
    defined = {}
    addresses = {}
    for path in source.sources():
        if not path.endswith(".cpp"):
            continue
        text = source.read(path)
        for m in DEFINE_RE.finditer(text):
            defined.setdefault(m.group(1), path)
        addresses[path] = rules.addresses(text)
    for module in modules:
        path = defined.get(module["attach"])
        module["source"] = path
        module["addresses"] = addresses.get(path, [])
    return modules


def load(path):
    path = Path(path)
    if not path.exists():
        return {"client": [], "server": []}
    data = yamlish.load(path.read_text("utf-8")) or {}
    data.setdefault("client", [])
    data.setdefault("server", [])
    return data


def regenerate(path, source, ref_label=None):
    """Rewrite the client part from kaentake, keeping hand-written descriptions and the whole server part."""
    old = load(path)
    descriptions = {e.get("id"): e.get("description") for e in old.get("client") or []}
    client = []
    for m in scan_client(source):
        client.append({"id": m["id"], "title": m["title"], "description": descriptions.get(m["id"]) or m["title"],
                       "default": m["default"], "flags": m["flags"], "requires": m["requires"],
                       "source": m["source"], "addresses": m["addresses"]})
    data = {"client_source": {"repo": "kaentake", "ref": ref_label or source.ref or "work tree",
                              "commit": source.commit[:12]},
            "client": client, "server": old.get("server") or []}
    Path(path).write_text(yamlish.dump(data, INVENTORY_HEADER), "utf-8", newline="\n")
    return data


def entries(inventory):
    """Every inventory entry as {id, side, title, description}: what judgments match against."""
    out = []
    for e in inventory.get("client") or []:
        out.append({"id": e["id"], "side": "client", "title": e.get("title") or e["id"],
                    "description": e.get("description") or e.get("title") or e["id"],
                    "core": "core" in (e.get("flags") or [])})
    for e in inventory.get("server") or []:
        out.append({"id": e["id"], "side": e.get("side") or "server", "title": e.get("title") or e["id"],
                    "description": e.get("description") or e.get("title") or e["id"], "core": False})
    return out


def address_owners(inventory):
    """v83 address -> ids of our client modules whose source names it."""
    owners = {}
    for e in inventory.get("client") or []:
        for address in e.get("addresses") or []:
            owners.setdefault(address, set()).add(e["id"])
    return owners


def server_paths(inventory):
    return {e["id"]: list(e.get("paths") or []) for e in inventory.get("server") or []}
