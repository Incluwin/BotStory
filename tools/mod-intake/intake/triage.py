"""P3 triage: dossiers + rule hints + Jev judgments -> one catalog entry per release, with corrections on top.

    catalog/mods.yaml        generated, committed: metadata only (ids, titles, authors, links and pins, kind,
                             version, family, status, probabilities); never message text or code
    catalog/overrides.yaml   corrections by thread id, kept by hand or by the board; applied on every run
    catalog/inventory.yaml   what BotStory already has (intake/inventory.py)

The policy (decide) is plain code over the judgments, so thresholds can change without asking Jev again.
"""
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import dossier as dossierlib
from . import inventory as invlib
from . import jev as jevlib
from . import yamlish

STATUSES = ("candidate", "skipped", "porting", "ported", "shipped")
SURE = 0.6            # a choice this probable decides; below it the entry is marked for review
VERY_SURE = 0.9       # a skip resting on a judgment below this is marked for review
INCLUDES_YES = 0.5
OVERRIDE_FIELDS = {
    "id": None, "status": STATUSES, "reason": None, "kind": jevlib.KINDS, "version": jevlib.VERSIONS,
    "family": jevlib.FAMILIES, "applies": jevlib.APPLIES, "match": None, "review": (True, False), "note": None,
    "client_feature": None, "server_mod": None, "replies": None,
}
MODS_HEADER = """BotStory mod catalog (P3): one entry per release thread of the M. Development C. releases section.
Generated by 'mod_intake.py triage'. Do not edit: corrections go in overrides.yaml (or through the board), which
every run applies on top. Metadata only: message text and code stay in the local data folder.
status: candidate | skipped (reason) | porting | ported | shipped. review: true = a person should look.
client_feature = the kaentake feature_list.h id once ported (P4); server_mod = the server.mods id once ported (P5).
judged: Jev probabilities (choices: options >= 0.01; includes: per-kind yes probability)."""
OVERRIDES_HEADER = """Corrections to the triage, by thread id (forum threads) or post-<message id> (text channel posts).
Every 'mod_intake.py triage' run applies these on top of what rules and judgments say, so they survive re-runs.
The board (mod_intake.py board --serve) writes this file; hand edits work too.
Fields: id status reason kind version family applies match review note client_feature server_mod
        replies: {<message id>: fix | bug_report | neither}
status: candidate | skipped | porting | ported | shipped"""


@dataclass
class Result:
    unit_id: str
    kind: str = None
    includes: list = field(default_factory=list)
    version: str = None
    family: str = None
    applies: str = None
    match: str = None
    replies: dict = field(default_factory=dict)   # message id -> {class, p}
    status: str = "candidate"
    reason: str = None
    review: bool = False
    why: list = field(default_factory=list)
    judged: dict = None                            # probabilities for the catalog
    complete: bool = False                         # every request of the unit has an answer


# Judgments

def gather(requests, cache, model):
    """unit id -> {answers: {qid: answer}, replies: {qid: message id}, parts, answered, model}; cached answers only."""
    by_unit = {}
    for r in requests:
        u = by_unit.setdefault(r.unit_id, {"answers": {}, "reply_answers": {}, "parts": 0, "answered": 0,
                                           "model": None})
        u["parts"] += 1
        hit = cache.get(r.key(model))
        if not hit:
            continue
        u["answered"] += 1
        u["model"] = hit["model"]
        for qid, answer in hit["answers"].items():
            if qid in r.replies:
                u["reply_answers"][r.replies[qid]] = answer
            elif r.part == "main":
                u["answers"][qid] = answer
    return by_unit


def _top(answer):
    if not answer:
        return None, 0.0
    probs = answer.get("probabilities") or {}
    choice = answer.get("choice")
    return choice, float(probs.get(choice, answer.get("confidence") or 0.0))


def _probs(answer):
    probs = (answer or {}).get("probabilities") or {}
    return {k: round(float(v), 2) for k, v in sorted(probs.items(), key=lambda kv: -kv[1]) if float(v) >= 0.01}


# Policy

def decide(d, judgment):
    """Rules first, then judgments where they exist; every step leaves a line in why."""
    res = Result(d["id"])
    hints = d["hints"]
    rule_versions = {v for v, _ in hints["versions"]}
    title_other = [why for v, why in hints["versions"] if v == "other" and why.startswith("title")]
    title_v83 = any(v == "v83" and why.startswith("title") for v, why in hints["versions"])
    answers = (judgment or {}).get("answers") or {}
    res.complete = bool(judgment) and judgment["answered"] == judgment["parts"]
    res.why.extend("rule: " + w for w in hints["why"])
    for v, why in hints["versions"]:
        res.why.append(f"rule: version {v} ({why})")
    for f, why in hints["families"]:
        res.why.append(f"rule: family {f} ({why})")

    if answers.get("kind"):
        res.judged = {"model": judgment.get("model")}
        for qid in ("kind", "version", "family", "applies", "match"):
            if answers.get(qid):
                res.judged[qid] = _probs(answers[qid])
        res.judged["includes"] = {k: round(float(answers["includes_" + k]["noul"]), 2) for k in jevlib.MOD_KINDS
                                  if answers.get("includes_" + k)}
        kind, p_kind = _top(answers["kind"])
        version, p_version = _top(answers.get("version"))
        family, p_family = _top(answers.get("family"))
        applies, p_applies = _top(answers.get("applies"))
        match, p_match = _top(answers.get("match"))
        res.kind, res.version, res.family, res.applies = kind, version, family, applies
        res.match = None if match in (None, "none") else match
        res.includes = [k for k, p in res.judged["includes"].items() if p >= INCLUDES_YES]
        if kind not in res.includes and kind in jevlib.MOD_KINDS:
            res.includes.insert(0, kind)
        res.why.append(f"jev: kind {kind} ({p_kind:.2f}), version {version} ({p_version:.2f}), family {family} "
                       f"({p_family:.2f}), applies {applies} ({p_applies:.2f})"
                       + (f", closest {match}" if res.match else ""))
        for qid, p in (("kind", p_kind), ("version", p_version)):
            if p < SURE:
                res.review = True
                res.why.append(f"review: {qid} is uncertain ({p:.2f})")
        if version == "v83" and title_other and p_version < 0.9:
            res.review = True
            res.why.append("review: the title names another version but Jev says v83")
        if version == "other" and "v83" in rule_versions and not title_other:
            res.review = True
            res.why.append("review: rules found v83 evidence but Jev says another version")
        if applies == "conflicts":
            res.review = True
            res.why.append("review: may conflict with " + (res.match or "one of our mods"))
        if not res.complete:
            res.review = True
            res.why.append(f"review: {judgment['parts'] - judgment['answered']} of {judgment['parts']} requests "
                           "not answered yet")
        skip = None
        if kind == "not_a_mod" and p_kind >= SURE:
            skip = ("not a mod", p_kind)
        elif version == "other" and p_version >= SURE and (p_version >= VERY_SURE or not title_v83):
            skip = ("made for another game version" + (f" ({title_other[0][len('title says '):]})"
                                                       if title_other else ""), p_version)
        elif applies == "already_have" and p_applies >= SURE and res.match:
            skip = (f"already have it: {res.match}", min(p_applies, p_match))
        if skip:
            res.status, res.reason = "skipped", skip[0]
            if skip[1] < VERY_SURE:
                res.review = True
                res.why.append(f"review: skipped on a judgment of {skip[1]:.2f} (below {VERY_SURE}); a person checks")
    else:
        res.kind = hints["kinds"][0] if hints["kinds"] else None
        res.includes = list(hints["kinds"])
        if title_other and "v83" not in [v for v, w in hints["versions"] if w.startswith("title")]:
            res.version = "other"
        elif "v83" in rule_versions:
            res.version = "v83"
        elif rule_versions:
            res.version = "other"
        else:
            res.version = "unknown"
        families = [f for f, _ in hints["families"]]
        res.family = families[0] if families else ("no_server_part" if res.kind in ("client_hook", "client_wz")
                                                   else None)
        res.review = True
        res.why.append("review: not judged by Jev yet (rules only)")
        if res.version == "other" and title_other:
            res.status, res.reason = "skipped", f"made for another game version ({title_other[0][len('title says '):]})"

    merged = _merged_changes(d)
    if merged and res.status == "candidate":
        res.status, res.reason = "skipped", "already in our server history"
        res.applies = "already_have"
        res.why.append("rule: every commit the release links is already in the BotStory server repo")

    for r in d.get("replies") or []:
        answer = ((judgment or {}).get("reply_answers") or {}).get(r["id"])
        if answer:
            cls, p = _top(answer)
            res.replies[r["id"]] = {"class": cls, "p": round(p, 2)}
    return res


def _merged_changes(d):
    starter = d.get("starter") or {}
    changes = [link for link in starter.get("links") or [] if link.get("in_botstory_history") is not None]
    return bool(changes) and all(link["in_botstory_history"] for link in changes)


# Catalog

def slug(title, fallback):
    text = re.sub(r"\[[^\]]*\]|\([^)]*\)", " ", title or "")
    words = re.findall(r"[a-z0-9]+", text.lower())
    out = ""
    for w in words:
        nxt = (out + "_" + w) if out else w
        if len(nxt) > 40:
            break
        out = nxt
    if not out or out[0].isdigit():
        out = "mod_" + (out or fallback[-6:])
    return out


def assign_ids(dossiers, previous, overrides):
    """Thread -> mod id: an override, else the id an earlier catalog gave it, else a new slug of the title."""
    ids, taken = {}, set()
    for d in dossiers:
        fixed = (overrides.get(d["id"]) or {}).get("id") or previous.get(d["id"])
        if fixed:
            ids[d["id"]] = fixed
            taken.add(fixed)
    for d in dossiers:
        if d["id"] in ids:
            continue
        base = slug(d["title"], d["id"])
        mod_id, n = base, 2
        while mod_id in taken:
            mod_id, n = f"{base}_{n}", n + 1
        ids[d["id"]] = mod_id
        taken.add(mod_id)
    return ids


def entry(d, res, mod_id):
    """The catalog entry: metadata only."""
    starter = d.get("starter") or {}
    sources = []
    for m, origin in [(starter, "release")] + [(r, "reply") for r in d.get("replies") or []]:
        for link in m.get("links") or []:
            snap = link.get("snapshot") or {}
            src = {"url": link["url"], "kind": link["kind"], "from": origin, "message": m.get("id"),
                   "status": snap.get("status") or "not_fetched", "pin": snap.get("pinned_sha"),
                   "base": snap.get("base_sha")}
            if snap.get("ref"):
                src["ref"] = snap["ref"]
            if link.get("in_botstory_history") is not None:
                src["in_our_history"] = link["in_botstory_history"]
            if link.get("files"):
                src["files"] = link["files"]["count"]
            if snap.get("status") in ("failed", "manual", "skipped"):
                src["detail"] = (snap.get("error") or snap.get("note") or "")[:200]
            sources.append({k: v for k, v in src.items() if v is not None})
    attachments = [{"file": a["filename"], "type": a["type"], "size": a["size"], "sha256": a["sha256"],
                    "from": origin, "message": m.get("id")}
                   for m, origin in [(starter, "release")] + [(r, "reply") for r in d.get("replies") or []]
                   for a in m.get("attachments") or []]
    counts = {c: 0 for c in jevlib.REPLY_CLASSES}
    for v in res.replies.values():
        counts[v["class"]] = counts.get(v["class"], 0) + 1
    out = {
        "id": mod_id,
        "thread": d["id"],
        "title": d["title"],
        "author": d["author"]["name"],
        "posted": (d.get("created_at") or "")[:10],
        "channel": d["channel"]["name"],
        "status": res.status,
        "reason": res.reason,
        "review": res.review,
        "kind": res.kind,
        "includes": res.includes,
        "version": res.version,
        "family": res.family,
        "applies": res.applies,
        "match": res.match,
        "client_feature": None,
        "server_mod": None,
        "sources": sources,
        "attachments": [{k: v for k, v in a.items() if v is not None} for a in attachments],
        "replies": {"total": len(d.get("replies") or []), **{k: v for k, v in counts.items() if v}},
        "fixes": [mid for mid, v in res.replies.items() if v["class"] == "fix"],
        "bug_reports": [mid for mid, v in res.replies.items() if v["class"] == "bug_report"],
        "rules": {"kinds": d["hints"]["kinds"], "versions": sorted({v for v, _ in d["hints"]["versions"]}),
                  "families": sorted({f for f, _ in d["hints"]["families"]}),
                  "addresses": len(d["evidence"]["release"]["addresses"])},
        "judged": res.judged,
        "dossier": d["hash"][:16],
    }
    return out


def apply_override(e, res, override):
    """Corrections win; the automatic values they replace stay visible under 'auto'."""
    if not override:
        return e
    auto = {}
    for key, value in override.items():
        if key in ("id", "note", "replies"):
            continue
        if key in e and e[key] != value:
            auto[key] = e[key]
        e[key] = value
    if override.get("note"):
        e["note"] = override["note"]
    for mid, cls in (override.get("replies") or {}).items():
        mid = str(mid)
        old = res.replies.get(mid, {}).get("class")
        res.replies[mid] = {"class": cls, "p": None, "corrected": True}
        if old != cls:
            auto.setdefault("replies", {})[mid] = old
    if override.get("replies"):
        e["fixes"] = [mid for mid, v in res.replies.items() if v["class"] == "fix"]
        e["bug_reports"] = [mid for mid, v in res.replies.items() if v["class"] == "bug_report"]
    if "status" in override and override["status"] != "skipped" and "reason" not in override:
        if e.get("reason") and auto.get("status") == "skipped":
            auto["reason"] = e["reason"]
            e["reason"] = None
    if "review" not in override:
        e["review"] = False  # a person looked at it
    e["overridden"] = sorted(k for k in override if k != "note")
    if auto:
        e["auto"] = auto
    return e


def load_overrides(path):
    path = Path(path)
    if not path.exists():
        return {}
    data = yamlish.load(path.read_text("utf-8")) or {}
    return {str(k): v for k, v in (data.get("overrides") or {}).items() if isinstance(v, dict)}


def validate_override(fields):
    """Raise ValueError for an unknown field or value; returns the cleaned fields (None and "" remove a field)."""
    clean = {}
    for key, value in fields.items():
        if key not in OVERRIDE_FIELDS:
            raise ValueError(f"unknown field {key!r} (allowed: {', '.join(sorted(OVERRIDE_FIELDS))})")
        allowed = OVERRIDE_FIELDS[key]
        if value in (None, ""):
            clean[key] = None
            continue
        if key == "replies":
            if not isinstance(value, dict):
                raise ValueError("replies must map message ids to fix, bug_report or neither")
            for mid, cls in value.items():
                if cls not in jevlib.REPLY_CLASSES:
                    raise ValueError(f"reply {mid}: {cls!r} is not one of {', '.join(jevlib.REPLY_CLASSES)}")
            clean[key] = {str(k): v for k, v in value.items()}
            continue
        if key == "id" and not re.match(r"^[a-z][a-z0-9_]{1,59}$", str(value)):
            raise ValueError("id must be snake_case: a-z, 0-9, _ (it names the mod/<id> branch and feature)")
        if allowed is not None and value not in allowed:
            raise ValueError(f"{key} must be one of {', '.join(str(a) for a in allowed)}")
        clean[key] = value if not isinstance(value, str) else value.strip()
    return clean


def save_override(path, unit_id, fields, replace=False):
    """Merge one thread's corrections into overrides.yaml (replace=True drops what was there first)."""
    clean = validate_override(fields)
    path = Path(path)
    data = load_overrides(path)
    current = {} if replace else dict(data.get(unit_id) or {})
    for key, value in clean.items():
        if value is None:
            current.pop(key, None)
        elif key == "replies":
            merged = dict(current.get("replies") or {})
            merged.update(value)
            current["replies"] = merged
        else:
            current[key] = value
    if current:
        data[unit_id] = current
    else:
        data.pop(unit_id, None)
    write_overrides(path, data)
    return current


def write_overrides(path, data):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    ordered = {k: data[k] for k in sorted(data, key=_unit_sort_key)}
    Path(path).write_text(yamlish.dump({"overrides": ordered}, OVERRIDES_HEADER), "utf-8", newline="\n")


def _unit_sort_key(unit_id):
    digits = re.sub(r"\D", "", unit_id)
    return (int(digits) if digits else 0, unit_id)


def previous_ids(path):
    path = Path(path)
    if not path.exists():
        return {}
    try:
        data = yamlish.load(path.read_text("utf-8")) or {}
    except yamlish.YamlError:
        return {}
    return {str(e.get("thread")): e.get("id") for e in data.get("mods") or [] if e.get("thread") and e.get("id")}


def write_catalog(path, entries, summary):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    data = {"summary": summary, "mods": entries}
    Path(path).write_text(yamlish.dump(data, MODS_HEADER), "utf-8", newline="\n")


# The run

@dataclass
class TriageRun:
    dossiers: list
    results: dict
    entries: list
    requests: list
    pending: list           # requests with no cached answer (after the run)
    asked: int = 0
    failed: list = field(default_factory=list)
    tokens: int = 0         # input tokens actually used this run
    notes: list = field(default_factory=list)
    judgments: dict = field(default_factory=dict)
    model: str = None


class Paths:
    """Where a run reads and writes. catalog_dir holds the committed files; data_dir the local ones."""

    def __init__(self, data_dir, catalog_dir):
        self.data_dir = Path(data_dir)
        self.catalog_dir = Path(catalog_dir)
        self.mods = self.catalog_dir / "mods.yaml"
        self.overrides = self.catalog_dir / "overrides.yaml"
        self.inventory = self.catalog_dir / "inventory.yaml"
        self.dossiers = self.data_dir / "dossiers"
        self.cache = self.data_dir / "triage.sqlite3"
        self.board = self.data_dir / "board.html"


def run(store, paths, jev=None, ask=False, model=None, write=True, limit=None, server_repo=None, git_env=None,
        log=print):
    """Build dossiers, judge what is not cached (ask=True and a JevClient), decide, and write the catalog.

    limit: judge at most this many threads this run. write=False (dry run) writes only the dossiers: no catalog,
    no API calls."""
    model = model or (jev.model if jev else jevlib.DEFAULT_MODEL)
    inventory = invlib.load(paths.inventory)
    our_mods = invlib.entries(inventory)
    dossiers, notes = dossierlib.build(store, paths.data_dir, inventory, server_repo, git_env)
    dossierlib.write(dossiers, paths.dossiers)
    requests = [r for d in dossiers for r in jevlib.requests_for(d, our_mods)]
    cache = jevlib.JudgmentCache(paths.cache)
    out = TriageRun(dossiers, {}, [], requests, [], notes=list(notes))
    try:
        pending = [r for r in requests if cache.get(r.key(model)) is None]
        if ask and write and jev is not None:
            todo = pending
            if limit:
                first = list(dict.fromkeys(r.unit_id for r in pending))[:limit]
                todo = [r for r in pending if r.unit_id in set(first)]
            for i, r in enumerate(todo, 1):
                try:
                    response = jev.ask(r)
                except jevlib.JevAuthError:
                    raise
                except jevlib.JevError as e:
                    out.failed.append((r.unit_id, r.part, str(e)))
                    log(f"  {r.unit_id} {r.part}: {e}")
                    continue
                cache.put(r.key(model), r, model, response)
                out.asked += 1
                out.tokens += (response.get("usage") or {}).get("input_tokens") or 0
                if i % 25 == 0:
                    log(f"  judged {i} of {len(todo)} requests")
            pending = [r for r in requests if cache.get(r.key(model)) is None]
        out.pending = pending
        judgments = gather(requests, cache, model)
    finally:
        cache.close()

    out.judgments = judgments
    out.model = model
    assemble(out, paths)
    if write:
        write_catalog(paths.mods, out.entries, summary(out.entries, model))
    return out


def assemble(out, paths):
    """Decide every unit from its dossier and cached judgment, then apply overrides. No git, no API: the board
    calls this again after each correction."""
    overrides = load_overrides(paths.overrides)
    ids = assign_ids(out.dossiers, previous_ids(paths.mods), overrides)
    out.results, out.entries = {}, []
    for d in out.dossiers:
        judgment = out.judgments.get(d["id"])
        res = decide(d, judgment if judgment and judgment["answered"] else None)
        e = apply_override(entry(d, res, ids[d["id"]]), res, overrides.get(d["id"]))
        out.results[d["id"]] = res
        out.entries.append(e)
    known = {d["id"] for d in out.dossiers}
    out.notes = [n for n in out.notes if not n.startswith("override for ")]
    for unit_id in overrides:
        if unit_id not in known:
            out.notes.append(f"override for {unit_id}: no such thread in the store (kept)")
    return out


def summary(entries, model):
    by_status = {}
    for e in entries:
        by_status[e["status"]] = by_status.get(e["status"], 0) + 1
    return {"entries": len(entries), "judged": sum(1 for e in entries if e.get("judged")),
            "review": sum(1 for e in entries if e.get("review")), "model": model,
            "status": dict(sorted(by_status.items()))}


def estimate(requests, model):
    tokens = sum(r.estimated_tokens(model) for r in requests)
    return {"requests": len(requests), "tokens": tokens, "usd": jevlib.cost_usd(tokens),
            "threads": len({r.unit_id for r in requests})}


def board_data(run_out, paths, inventory=None):
    """Everything the board shows, as one JSON-able dict (dossiers included: the board stays in the data folder)."""
    inventory = inventory if inventory is not None else invlib.load(paths.inventory)
    units = []
    entries = {e["thread"]: e for e in run_out.entries}
    for d in run_out.dossiers:
        res = run_out.results[d["id"]]
        units.append({"dossier": d, "entry": entries[d["id"]], "why": res.why, "replies": res.replies,
                      "complete": res.complete})
    return {"units": units, "inventory": invlib.entries(inventory),
            "options": {"status": list(STATUSES), "kind": list(jevlib.KINDS), "version": list(jevlib.VERSIONS),
                        "family": list(jevlib.FAMILIES), "applies": list(jevlib.APPLIES),
                        "reply": list(jevlib.REPLY_CLASSES)},
            "overrides": load_overrides(paths.overrides)}


def dump_json(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=False)
