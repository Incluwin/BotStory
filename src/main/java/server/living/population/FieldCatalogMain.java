package server.living.population;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Generates {@code fields.yaml} for the population from the server's WZ XML tree:
 * every open-world map on Victoria and Ossyria with its name, region, town flag, mob spawn
 * count, average mob level and a grinder capacity ({@code spawn entries / 4}, clamped 1..6),
 * with the Victoria field-capacity catalog's recommended maxima layered on top.
 * Instanced maps (a {@code forcedReturn}) and maps with fewer than four spawns are skipped.
 *
 * <p>{@code tools\population-fields.bat [wz-dir] [out.yaml]}. Pure file parsing, no database.
 */
public final class FieldCatalogMain {
    private static final Pattern LIFE_MOB = Pattern.compile(
            "<string name=\"type\" value=\"m\"/>\\s*<string name=\"id\" value=\"(\\d+)\"/>");
    private static final Pattern INT = Pattern.compile("<int name=\"%s\" value=\"(-?\\d+)\"/>");
    private static final Pattern MAP_NAME = Pattern.compile(
            "<imgdir name=\"(\\d+)\">\\s*(?:<string name=\"streetName\" value=\"([^\"]*)\"/>\\s*)?(?:<string name=\"mapName\" value=\"([^\"]*)\"/>)?");
    private static final int MIN_SPAWNS = 4;
    private static final int SPAWNS_PER_AGENT = 4;
    private static final int CAPACITY_MAX = 6;

    private FieldCatalogMain() {
    }

    public static void main(String[] args) throws IOException {
        Path wz = Path.of(args.length > 0 ? args[0] : "wz");
        Path out = Path.of(args.length > 1 ? args[1] : "scripts/config/population/fields.yaml");
        Map<Integer, String[]> names = mapNames(wz.resolve("String.wz/Map.img.xml"));
        Map<Integer, Integer> mobLevels = new HashMap<>();
        Map<Integer, Integer> victoriaMax = victoriaOverrides(Path.of("src/main/resources/agents/field/victoria-field-capacities.json"));
        StringBuilder yaml = new StringBuilder();
        yaml.append("# Open-world maps citizens may train in or visit. Generated by tools\\population-fields.bat from wz/;\n");
        yaml.append("# edit freely (the generator only adds maps it does not find). capacity = grinders the map holds at once.\n");
        yaml.append("fields:\n");
        int count = 0;
        for (String folder : new String[]{"Map1", "Map2"}) {
            Path dir = wz.resolve("Map.wz/Map/" + folder);
            if (!Files.isDirectory(dir)) {
                continue;
            }
            List<Path> files;
            try (Stream<Path> stream = Files.list(dir)) {
                files = stream.filter(file -> file.getFileName().toString().endsWith(".img.xml")).sorted().toList();
            }
            for (Path file : files) {
                int mapId = Integer.parseInt(file.getFileName().toString().replace(".img.xml", ""));
                String xml = Files.readString(file, StandardCharsets.UTF_8);
                int town = intOf(xml, "town", 0);
                int forcedReturn = intOf(xml, "forcedReturn", 999999999);
                String region = region(mapId);
                if (region == null) {
                    continue;
                }
                List<Integer> mobs = new ArrayList<>();
                Matcher life = LIFE_MOB.matcher(xml);
                while (life.find()) {
                    mobs.add(Integer.parseInt(life.group(1)));
                }
                if (town == 0 && (forcedReturn != 999999999 || mobs.size() < MIN_SPAWNS)) {
                    continue;
                }
                double levelSum = 0;
                int levelCount = 0;
                for (int mob : mobs) {
                    int level = mobLevels.computeIfAbsent(mob, id -> mobLevel(wz, id));
                    if (level > 0) {
                        levelSum += level;
                        levelCount++;
                    }
                }
                int mobLevel = levelCount == 0 ? 0 : (int) Math.round(levelSum / levelCount);
                int capacity = town == 1 ? 0 : Math.max(1, Math.min(CAPACITY_MAX, mobs.size() / SPAWNS_PER_AGENT));
                if (victoriaMax.containsKey(mapId)) {
                    capacity = victoriaMax.get(mapId);
                }
                String[] name = names.getOrDefault(mapId, new String[]{"", ""});
                if (name[1].startsWith("<Year") || name[1].startsWith("&lt;Year")) {
                    continue; // Neo City time-travel maps are quest gated
                }
                yaml.append("  - { mapId: ").append(mapId)
                        .append(", name: \"").append(quote(name[1].isEmpty() ? "map " + mapId : name[1]))
                        .append("\", street: \"").append(quote(name[0]))
                        .append("\", region: ").append(region)
                        .append(", town: ").append(town == 1)
                        .append(", mobs: ").append(mobs.size())
                        .append(", mobLevel: ").append(mobLevel)
                        .append(", capacity: ").append(capacity)
                        .append(" }\n");
                count++;
            }
        }
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, yaml.toString(), StandardCharsets.US_ASCII);
        System.out.println(count + " maps -> " + out.toAbsolutePath());
    }

    /** Region by map id prefix; null for maps citizens should not consider (events, PQs, GM maps). */
    static String region(int mapId) {
        int prefix = mapId / 1_000_000;
        return switch (prefix) {
            case 100, 101, 102, 103, 104, 105, 106 -> "victoria";
            case 110 -> "florina";
            case 120 -> "nautilus";
            case 200 -> "orbis";
            case 211 -> "el-nath";
            case 220 -> "ludibrium";
            case 221 -> "omega-sector";
            case 222 -> "korean-folk-town";
            case 230 -> "aquarium";
            case 240 -> "leafre";
            case 250 -> "mu-lung";
            case 251 -> "herb-town";
            case 260 -> "ariant";
            case 261 -> "magatia";
            default -> null;
        };
    }

    private static int intOf(String xml, String name, int fallback) {
        Matcher m = Pattern.compile(String.format(INT.pattern(), name)).matcher(xml);
        return m.find() ? Integer.parseInt(m.group(1)) : fallback;
    }

    private static int mobLevel(Path wz, int mobId) {
        Path file = wz.resolve(String.format("Mob.wz/%07d.img.xml", mobId));
        try {
            return Files.exists(file) ? intOf(Files.readString(file, StandardCharsets.UTF_8), "level", 0) : 0;
        } catch (IOException failure) {
            return 0;
        }
    }

    private static Map<Integer, String[]> mapNames(Path stringMap) throws IOException {
        Map<Integer, String[]> names = new HashMap<>();
        if (!Files.exists(stringMap)) {
            return names;
        }
        Matcher m = MAP_NAME.matcher(Files.readString(stringMap, StandardCharsets.UTF_8));
        while (m.find()) {
            names.put(Integer.parseInt(m.group(1)), new String[]{unescape(m.group(2)), unescape(m.group(3))});
        }
        return names;
    }

    private static Map<Integer, Integer> victoriaOverrides(Path catalog) {
        Map<Integer, Integer> out = new TreeMap<>();
        if (!Files.exists(catalog)) {
            return out;
        }
        try {
            Matcher m = Pattern.compile("\"mapId\":\\s*(\\d+).*?\"recommendedMaximum\":\\s*(\\d+)", Pattern.DOTALL)
                    .matcher(Files.readString(catalog, StandardCharsets.UTF_8));
            while (m.find()) {
                out.put(Integer.parseInt(m.group(1)), Integer.parseInt(m.group(2)));
            }
        } catch (IOException ignored) {
            // the generic estimate stands
        }
        return out;
    }

    private static String unescape(String s) {
        return s == null ? "" : s.replace("&apos;", "'").replace("&quot;", "\"").replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&");
    }

    private static String quote(String s) {
        StringBuilder out = new StringBuilder();
        for (char c : s.replace("\\", "").replace("\"", "'").toCharArray()) {
            out.append(c < 0x7f ? c : '?');
        }
        return out.toString();
    }
}
