package server.living.config;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import server.living.config.Content.Persona;
import server.living.config.Content.Quest;
import server.living.config.Content.Step;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Assigns stable client quest-log ids to living-world quests and exports the text the client
 * shows for them: {@code tools\living-world-questlog.bat [content-dir] [export.json]}.
 *
 * <p>Ids live in {@code quest-log-ids.yaml} next to the content (30000-32767, never renumbered;
 * new quests take the next free id). The JSON goes to MapleEdit, whose
 * {@code living_world_quests.py} writes the entries into Quest.wz (QuestInfo/Check/Act) and the
 * server XML; the runtime then mirrors ledger state into the client quest log when
 * {@code living_world.QUEST_LOG_MIRROR} is on.
 *
 * <p>How the client shows them (checked in a v83 client): the list groups quests by {@code area}
 * under a header named in Etc.wz {@code QuestCategory.img}, and labels each entry with
 * {@code parent} (else {@code name}) as plain text, colour codes printed literally; the detail pane
 * titles it with {@code name}, where {@code #b} renders blue.
 */
public final class QuestLogExportMain {
    /** The "Residents" group of the client's quest list: an unused QuestCategory.img slot MapleEdit names. */
    static final int AREA_RESIDENTS = 31;

    private QuestLogExportMain() {
    }

    public static void main(String[] args) throws IOException {
        Path root = Path.of(args.length > 0 ? args[0] : "scripts/config/living-world");
        Path export = Path.of(args.length > 1 ? args[1] : "target/living-quest-log.json");
        LivingContent content;
        try {
            content = ContentLoader.load(root);
        } catch (ContentException failure) {
            System.out.println("ERROR " + failure.getMessage());
            System.exit(1);
            return;
        }
        Map<String, Integer> ids = assignIds(content);
        writeIds(root.resolve(ContentLoader.QUEST_LOG_IDS_FILE), ids);

        List<Map<String, Object>> entries = new ArrayList<>();
        for (Quest quest : content.quests().values()) {
            entries.add(entry(content, quest, ids.get(quest.id())));
        }
        Files.createDirectories(export.toAbsolutePath().getParent());
        new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT).writeValue(export.toFile(), entries);
        System.out.println(entries.size() + " quests -> " + export.toAbsolutePath());
        System.out.println("ids in " + root.resolve(ContentLoader.QUEST_LOG_IDS_FILE).toAbsolutePath());
    }

    /** Existing ids are kept; quests without one get the lowest free id in content order. */
    static Map<String, Integer> assignIds(LivingContent content) {
        Map<String, Integer> ids = new LinkedHashMap<>();
        Set<Integer> used = new LinkedHashSet<>();
        for (Quest quest : content.quests().values()) {
            int existing = content.questLogId(quest.id());
            if (existing != 0 && used.add(existing)) {
                ids.put(quest.id(), existing);
            }
        }
        int next = ContentLint.QUEST_LOG_ID_MIN;
        for (Quest quest : content.quests().values()) {
            if (ids.containsKey(quest.id())) {
                continue;
            }
            while (used.contains(next)) {
                next++;
            }
            if (next > ContentLint.QUEST_LOG_ID_MAX) {
                throw new ContentException("out of quest-log ids");
            }
            used.add(next);
            ids.put(quest.id(), next);
        }
        return ids;
    }

    private static void writeIds(Path file, Map<String, Integer> ids) throws IOException {
        StringBuilder yaml = new StringBuilder();
        yaml.append("# Client quest-log ids (Quest.wz) for living-world quests. Generated by\n");
        yaml.append("# tools\\living-world-questlog.bat; ids are stable once assigned - do not renumber.\n");
        yaml.append("ids:\n");
        for (Map.Entry<String, Integer> entry : ids.entrySet()) {
            yaml.append("  ").append(entry.getKey()).append(": ").append(entry.getValue()).append('\n');
        }
        Files.writeString(file, yaml.toString(), StandardCharsets.US_ASCII);
    }

    static Map<String, Object> entry(LivingContent content, Quest quest, int logId) {
        Persona giver = content.persona(quest.persona());
        String giverName = giver == null ? quest.persona() : giver.name();
        String town = giver == null ? "" : giver.homeTown().replace('-', ' ');
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("logId", logId);
        out.put("questId", quest.id());
        out.put("name", "#b" + quest.title() + "#k"); // the detail pane's title, in blue
        out.put("parent", quest.title()); // the list label (plain text there)
        out.put("area", AREA_RESIDENTS);
        out.put("lvmin", Math.max(1, quest.requires().minLevel())); // shown as "Over Level N" in the detail pane
        out.put("npc", content.portraitNpcId(quest.persona())); // the giver's own portrait in the detail pane; 0 = none
        out.put("available", firstLine(giver, "questOffer." + quest.id(),
                "Ask " + giverName + " in " + capitalize(town) + " about it."));
        out.put("inProgress", giverName + " (" + capitalize(town) + "): " + steps(content, quest));
        out.put("completed", firstLine(giver, "questComplete." + quest.id(), "Done. " + giverName + " was grateful."));
        return out;
    }

    private static String firstLine(Persona persona, String intent, String fallback) {
        if (persona != null && persona.dialogue() != null) {
            List<String> lines = persona.dialogue().get(intent);
            if (lines != null && !lines.isEmpty()) {
                return lines.get(0);
            }
        }
        return fallback;
    }

    private static String steps(LivingContent content, Quest quest) {
        StringBuilder text = new StringBuilder();
        for (Step step : quest.steps()) {
            if (text.length() > 0) {
                text.append(" -> ");
            }
            text.append(describe(content, quest, step));
        }
        return text.toString();
    }

    private static String describe(LivingContent content, Quest quest, Step step) {
        String giver = personaName(content, quest.persona());
        return switch (step.type()) {
            case TALK -> "talk to " + giver;
            case KILL_MOBS, KILL_BOSS -> "defeat " + step.count() + " " + mobName(step.mobIds())
                    + (step.with() != null ? " with " + personaName(content, step.with()) : "");
            case HUNT_WITH -> "hunt " + step.count() + " " + mobName(step.mobIds()) + " with " + personaName(content, step.persona());
            case COLLECT_ITEM -> "collect " + step.count() + " " + (step.label() != null ? step.label() : itemName(step.itemId()));
            case DELIVER -> "bring " + (step.take() == null ? "word" : itemName(step.take().itemId()) + " x" + step.take().count())
                    + " to " + personaName(content, step.to());
            case VISIT_MAP -> "visit map " + step.mapIds().get(0);
            case TALK_TO -> "talk to " + personaName(content, step.persona());
            case HEAR_RUMOR -> "learn what the townsfolk say";
            case ESCORT -> "escort " + personaName(content, step.persona());
            case PAY -> "pay " + step.meso() + " meso";
            case GIVE_ITEM -> "hand over " + step.count() + " " + itemName(step.itemId());
            case REACH_LEVEL -> "reach level " + step.level();
            case WAIT -> "come back in " + step.hours() + " hour(s)";
            case PARTY_QUEST_CLEAR -> "clear a party quest" + (step.to() == null ? "" : " (" + step.to() + ")");
        };
    }

    private static String personaName(LivingContent content, String id) {
        if (id == null) {
            return "them";
        }
        if (id.startsWith("npc:")) {
            return "the NPC";
        }
        Persona persona = content.persona(id);
        return persona == null ? id : persona.name();
    }

    /** String.wz without the item/mob providers, which need a database connection to initialise. */
    private static final provider.DataProvider STRINGS = provider.DataProviderFactory.getDataProvider(provider.wz.WZFiles.STRING);

    private static String itemName(int itemId) {
        try {
            String id = String.valueOf(itemId);
            provider.Data node = null;
            switch (itemId / 1_000_000) {
                case 1 -> {
                    provider.Data eqp = STRINGS.getData("Eqp.img").getChildByPath("Eqp");
                    for (provider.Data category : eqp.getChildren()) {
                        node = category.getChildByPath(id);
                        if (node != null) {
                            break;
                        }
                    }
                }
                case 2 -> node = STRINGS.getData("Consume.img").getChildByPath(id);
                case 3 -> node = STRINGS.getData("Ins.img").getChildByPath(id);
                case 4 -> node = STRINGS.getData("Etc.img").getChildByPath("Etc/" + id);
                case 5 -> {
                    node = STRINGS.getData("Cash.img").getChildByPath(id);
                    if (node == null) {
                        node = STRINGS.getData("Pet.img").getChildByPath(id);
                    }
                }
                default -> { }
            }
            String name = node == null ? null : provider.DataTool.getString("name", node, null);
            return name == null ? "item " + itemId : name;
        } catch (Throwable unavailable) {
            return "item " + itemId; // no WZ data on this classpath
        }
    }

    private static String mobName(List<Integer> mobIds) {
        if (mobIds == null || mobIds.isEmpty()) {
            return "monsters";
        }
        try {
            provider.Data node = STRINGS.getData("Mob.img").getChildByPath(String.valueOf(mobIds.get(0)));
            String name = node == null ? null : provider.DataTool.getString("name", node, null);
            return (name == null ? "monsters" : name) + (mobIds.size() > 1 ? " and the like" : "");
        } catch (Throwable unavailable) {
            return "monsters";
        }
    }

    private static String capitalize(String words) {
        StringBuilder out = new StringBuilder();
        for (String word : words.split(" ")) {
            if (word.isEmpty()) {
                continue;
            }
            if (out.length() > 0) {
                out.append(' ');
            }
            out.append(Character.toUpperCase(word.charAt(0))).append(word.substring(1).toLowerCase(Locale.ROOT));
        }
        return out.toString();
    }
}
