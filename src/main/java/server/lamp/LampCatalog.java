    static {
        // All four arrays are indexed by the byte sent over LP_LampPreview. Failing on
        // startup turns a generator/merge mismatch into an actionable error instead of
        // a preview of the wrong sprite.
        if (NAMES.length != PATHS.length || NAMES.length != LIGHTS.length || NAMES.length != WHERE.length) {
            throw new IllegalStateException("Lamp catalog arrays are not index-aligned");
        }
        if (NAMES.length > 256) {
            throw new IllegalStateException("Lamp catalog no longer fits the one-byte preview id");
        }
    }

    public static int size() {
        return NAMES.length;
    }

    public static boolean isValid(int id) {
        return id >= 0 && id < NAMES.length;
    }
